"""Generate a SYNTHETIC COD-order dataset and fit the RTO-risk model used by the Pakka demo.

Everything here is synthetic. The data-generating weights below are assumptions written for the demo,
not measurements from any real brand, courier or marketplace.

Run:  python model/train_model.py
Outputs: data/synthetic_cod_orders.csv, model/weights.json, docs/weights.js, model/metrics.json
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parents[1]
SEED = 42
N = 20_000

FEATURES = [
    "first_time_customer",   # 1 if no previous delivered order
    "pincode_tier_3",        # 1 if the delivery pincode is in a tier-3 / rural area (synthetic flag)
    "order_value_k",         # order value in thousands of INR
    "address_quality",       # 0-1 score from an address-completeness check (landmark, house no., valid pincode)
    "late_night_order",      # 1 if placed between 11pm and 5am
    "past_rto_count",        # previous returned-to-origin orders for this phone number (capped at 3)
    "discount_pct",          # discount applied, 0-60
    "phone_verified",        # 1 if the shopper confirmed the order on WhatsApp/OTP
]


def make_data(n=N, seed=SEED):
    rng = np.random.default_rng(seed)
    df = pd.DataFrame({
        "first_time_customer": rng.binomial(1, 0.62, n),
        "pincode_tier_3": rng.binomial(1, 0.35, n),
        "order_value_k": np.round(rng.gamma(2.2, 0.55, n) + 0.2, 2),
        "address_quality": np.round(rng.beta(4, 1.6, n), 2),
        "late_night_order": rng.binomial(1, 0.18, n),
        "past_rto_count": np.minimum(rng.poisson(0.25, n), 3),
        "discount_pct": np.round(rng.choice([0, 10, 20, 30, 40, 50], n, p=[.25, .2, .2, .15, .12, .08]), 0),
        "phone_verified": rng.binomial(1, 0.45, n),
    })
    # Assumed "true" relationship for the synthetic world (illustrative only).
    logit = (-2.3 + 0.65 * df.first_time_customer + 0.55 * df.pincode_tier_3 + 0.22 * df.order_value_k
             - 1.9 * (df.address_quality - 0.7) + 0.45 * df.late_night_order + 0.8 * df.past_rto_count
             + 0.018 * df.discount_pct - 0.9 * df.phone_verified)
    p = 1 / (1 + np.exp(-logit))
    df["rto"] = rng.binomial(1, p)
    df.insert(0, "order_id", [f"SYN-{i:05d}" for i in range(n)])
    return df


def lift_at(y_true, scores, frac=0.2):
    order = np.argsort(-scores)
    top = order[: int(len(order) * frac)]
    return float(y_true[top].mean() / y_true.mean()), float(y_true[top].sum() / y_true.sum())


def main():
    df = make_data()
    (ROOT / "data").mkdir(exist_ok=True)
    df.to_csv(ROOT / "data" / "synthetic_cod_orders.csv", index=False)

    X, y = df[FEATURES].values, df["rto"].values
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.25, random_state=SEED, stratify=y)
    clf = LogisticRegression(max_iter=2000).fit(X_tr, y_tr)
    scores = clf.predict_proba(X_te)[:, 1]
    lift, capture = lift_at(y_te, scores, 0.2)
    metrics = {
        "rows": int(len(df)),
        "synthetic_rto_rate": round(float(y.mean()), 4),
        "holdout_auc": round(float(roc_auc_score(y_te, scores)), 4),
        "top20_lift": round(lift, 3),
        "top20_share_of_rtos_caught": round(capture, 3),
        "note": "Synthetic data. These numbers describe the demo model on made-up orders, not real-world performance.",
    }
    weights = {"intercept": round(float(clf.intercept_[0]), 4),
               "coef": {f: round(float(c), 4) for f, c in zip(FEATURES, clf.coef_[0])},
               # Training-set averages, used to explain each score relative to a typical COD order.
               "means": {f: round(float(df[f].mean()), 4) for f in FEATURES}}
    (ROOT / "model" / "weights.json").write_text(json.dumps(weights, indent=2) + "\n")
    (ROOT / "model" / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    (ROOT / "docs" / "weights.js").write_text(
        "// Auto-generated by model/train_model.py from SYNTHETIC data. Do not edit by hand.\n"
        f"window.PAKKA_WEIGHTS = {json.dumps(weights)};\nwindow.PAKKA_METRICS = {json.dumps(metrics)};\n")
    print(json.dumps({"weights": weights, "metrics": metrics}, indent=2))


if __name__ == "__main__":
    main()
